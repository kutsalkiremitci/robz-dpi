// Rusça çoğul biçimleri: 1 сайт, 2 сайта, 5 сайтов.
function plural(n, one, few, many) {
  const tens = Math.abs(n) % 100;
  const ones = tens % 10;
  if (tens > 10 && tens < 20) return many;
  if (ones === 1) return one;
  if (ones > 1 && ones < 5) return few;
  return many;
}

